# Lag en dictionary elev med nøklene "navn", "klasse" og "alder", og fyll inn selvvalgte verdier. 
# Skriv ut navnet og klassen med hver sin print()


# Et dictionary inni en liste
elev = [
{"Navn":"Kaspar", "Klasse":"2STG", "Alder":"17"}
]
print(elev[0]["Navn"], elev[0]["Klasse"])

# Bare et dictionary
elev = {"Navn":"Kaspar", "Klasse":"2STG", "Alder":"17"}
print(elev["Navn"], elev["Klasse"])

